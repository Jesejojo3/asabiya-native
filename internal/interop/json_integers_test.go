func TestProtocolExactIntegers(t *testing.T) {
	for _, tc := range []struct{ input, want string }{
		{"4.0", "4"}, {"400.0", "400"}, {"200.0", "200"},
		{"40e-1", "4"}, {"0.400e1", "4"}, {"4E+0", "4"},
		{"-9000.000", "-9000"}, {"-0.0", "-0"}, {"0e999999999999999999", "0"},
		{"9007199254740993.0", "9007199254740993"},
		{"9223372036854775807.0", "9223372036854775807"},
		{"-9223372036854775808.0", "-9223372036854775808"},
		{"4.5", ""}, {"4.0000000000000001", ""},
		{"9007199254740992.5", ""}, {"1e-999999999999999", ""},
		{"1e999999999999999", ""}, {"1e1000000", ""},
		{"9223372036854775808.0", ""}, {"-9223372036854775809.0", ""},
		{"1.0e20", ""}, {`"4.0"`, ""}, {"true", ""}, {"4.0 5.0", ""},
	} {
		t.Run(tc.input, func(t *testing.T) {
			var got int64
			err := decodePayload([]byte(tc.input), &got)
			if tc.want == "" {
				if err == nil {
					t.Fatalf("accepted invalid integer %s as %d", tc.input, got)
				}
				return
			}
			var want int64
			if err != nil || json.Unmarshal([]byte(tc.want), &want) != nil || got != want {
				t.Fatalf("got %d, %v; want %s", got, err, tc.want)
			}
			encoded, err := json.Marshal(got)
			if err != nil || strings.ContainsAny(string(encoded), ".eE") {
				t.Fatalf("response integer not canonical: %s, %v", encoded, err)
			}
		})
	}
	for _, tc := range []struct {
		input string
		valid bool
	}{
		{"18446744073709551615.0", true}, {"18446744073709551616.0", false},
		{"-1.0", false}, {"1.5", false}, {"1.00000000000000001", false},
	} {
		var got uint64
		if err := decodePayload([]byte(tc.input), &got); (err == nil) != tc.valid {
			t.Fatalf("uint64 %s: %d, %v", tc.input, got, err)
		}
	}
	for _, raw := range []string{"2147483648.0", "-2147483649.0", "4.5"} {
		var cell sim.CellID
		if err := decodePayload([]byte(raw), &cell); err == nil {
			t.Fatalf("CellID accepted %s", raw)
		}
	}
}

func TestProtocolNumberAdaptationPreservesOtherJSON(t *testing.T) {
	for _, raw := range []string{
		"0.33", "4.5", "4.0000000000000001", "9007199254740993.0", "1e19",
		"-0.0", "0.0", "1e-300", "1e300", "0.00000000000000000001", "-9000.00",
	} {
		var before, after float64
		if err := json.Unmarshal([]byte(raw), &before); err != nil {
			t.Fatal(err)
		}
		if err := decodePayload([]byte(raw), &after); err != nil || math.Float64bits(before) != math.Float64bits(after) {
			t.Fatalf("float changed: %s, %v", raw, err)
		}
	}
	// Strings/escapes, member order, repeated members and non-integral floats
	// are copied verbatim; unlike decoding to map[string]any, no keys are lost.
	raw := []byte(`{"4.0":"quote\" 400.0 \\ 4e0","n":4.0,"n":4.5}`)
	want := `{"4.0":"quote\" 400.0 \\ 4e0","n":4,"n":4.5}`
	if got := string(normalizeJSONIntegers(raw)); got != want {
		t.Fatalf("JSON changed: %s", got)
	}
	for _, raw := range []string{`{"id":4.0,"extra":1}`, `{"id":4.5}`, `{"id":1e999999}`, `{"id":"4.0"}`} {
		var payload struct {
			ID int `json:"id"`
		}
		if err := decodePayload([]byte(raw), &payload); err == nil {
			t.Fatalf("accepted invalid payload %s", raw)
		}
	}
	for _, raw := range []string{`{"session":1.5}`, `{"session":-1.0}`, `{"session":18446744073709551616.0}`, `{"id":1.0}`, `{"session":01.0}`} {
		var req Request
		if err := json.Unmarshal([]byte(raw), &req); err == nil {
			t.Fatalf("accepted invalid envelope %s", raw)
		}
	}
}

func TestProtocolIntegerFieldRejections(t *testing.T) {
	for _, raw := range []string{
		`{"world":{"width":400.5}}`, `{"world":{"height":200.5}}`,
		`{"world":{"detail":4.0000000000000001}}`,
		`{"command":{"sequence":-1.0}}`, `{"command":{"sequence":18446744073709551616.0}}`,
		`{"command":{"targetYear":-9000.5}}`, `{"command":{"targetYear":9223372036854775808.0}}`,
		`{"command":{"cell":12.5}}`, `{"command":{"cell":2147483648.0}}`,
		`{"source":{"assets":[{"bytes":1553001.5}]}}`,
		`{"source":{"assets":[{"bytes":9223372036854775808.0}]}}`,
	} {
		var payload struct {
			World   sim.WorldConfig `json:"world"`
			Command sim.Command     `json:"command"`
			Source  sim.WorldSource `json:"source"`
		}
		if err := decodePayload([]byte(raw), &payload); err == nil {
			t.Fatalf("integer field accepted invalid number: %s", raw)
		}
	}
}

// This fixture is generated by Godot itself using JSON.parse_string followed
// by JSON.stringify, the same float-valued configuration path as bridge_source.
func TestProtocolGodotSerializationFixture(t *testing.T) {
	raw, err := os.ReadFile("testdata/godot-integer-requests.json")
	if err != nil {
		t.Fatal(err)
	}
	var fixtures []Request
	if err := json.Unmarshal(raw, &fixtures); err != nil {
		t.Fatal(err)
	}
	if len(fixtures) != 6 || !strings.Contains(string(raw), `400.0`) {
		t.Fatal("expected six real Godot fixtures including decimal dimensions")
	}
	var world struct {
		World sim.WorldConfig `json:"world"`
	}
	if err := decodePayload(fixtures[0].Payload, &world); err != nil || world.World.Width != 400 || world.World.Height != 200 || world.World.Detail != 4 || world.World.LandFraction != .33 {
		t.Fatalf("world: %+v, %v", world, err)
	}
	var command sim.Command
	if err := decodePayload(fixtures[1].Payload, &command); err != nil || command.Sequence != 1 || command.TargetYear != -9000 || command.Cell != 12 || command.Values["volcano"] != .125 {
		t.Fatalf("command: %+v, %v", command, err)
	}
	var province struct {
		ID sim.CellID `json:"id"`
	}
	if err := decodePayload(fixtures[2].Payload, &province); err != nil || province.ID != 12 {
		t.Fatalf("province: %+v, %v", province, err)
	}
	var year struct {
		Year int `json:"year"`
	}
	if err := decodePayload(fixtures[3].Payload, &year); err != nil || year.Year != -9000 {
		t.Fatalf("year: %+v, %v", year, err)
	}
	var entity struct {
		Kind string `json:"kind"`
		ID   int    `json:"id"`
	}
	if err := decodePayload(fixtures[4].Payload, &entity); err != nil || entity.ID != 12 || fixtures[4].Session != 2 {
		t.Fatalf("entity: %+v, %v", entity, err)
	}
	var source struct {
		Source sim.WorldSource `json:"source"`
	}
	source.Source = sim.DefaultWorldSource()
	if err := decodePayload(fixtures[5].Payload, &source); err != nil || len(source.Source.Assets) != 1 || source.Source.Assets[0].Bytes != 1553001 || source.Source.Climate.Dry != .038 {
		t.Fatalf("source: %+v, %v", source, err)
	}
	for _, req := range fixtures {
		encoded, err := json.Marshal(req)
		var roundTrip Request
		if err != nil || json.Unmarshal(encoded, &roundTrip) != nil || roundTrip.Session != req.Session || roundTrip.ID != req.ID {
			t.Fatalf("envelope round trip: %s, %v", encoded, err)
		}
	}
}

func TestProtocolGodotIntegersOnConnection(t *testing.T) {
	client, server := net.Pipe()
	t.Cleanup(func() { client.Close() })
	if err := client.SetDeadline(time.Now().Add(30 * time.Second)); err != nil {
		t.Fatal(err)
	}
	session := &Session{}
	done := make(chan error, 1)
	go func() {
		defer server.Close()
		shutdown, err := serveConnection(context.Background(), server, session)
		if err == nil && !shutdown {
			err = fmt.Errorf("missing shutdown")
		}
		done <- err
	}()
	reader := bufio.NewReader(client)
	call := func(op, payload, sessionID string) Response {
		t.Helper()
		if _, err := fmt.Fprintf(client, `{"schema":"asabiya/local-v1","id":"test","session":%s,"op":%q,"payload":%s}`+"\n", sessionID, op, payload); err != nil {
			t.Fatal(err)
		}
		line, err := reader.ReadBytes('\n')
		if err != nil {
			t.Fatal(err)
		}
		var response Response
		if err := json.Unmarshal(line, &response); err != nil {
			t.Fatal(err)
		}
		return response
	}
	ok := func(r Response) {
		t.Helper()
		if !r.OK {
			t.Fatalf("request rejected: %+v", r.Error)
		}
	}
	// Generate only a small real world. Full 400x200 configuration is decoded
	// above; this scoped regression does not run the historical test suites.
	world := `{"world":{"seed":"Godot contract","width":24.0,"height":16.0,"detail":4.0,"landFraction":0.33},"fine":false}`
	ok(call("create_world", world, "0.0"))
	ok(call("start_history", `{"historySeed":"1","view":"map"}`, "1.0"))
	for _, op := range []string{"get_province", "get_province_history"} {
		ok(call(op, `{"id":0.0}`, "2.0"))
	}
	// Missing entities/layers are domain errors, not decoding errors.
	for _, tc := range []struct{ op, payload string }{
		{"get_entity", `{"kind":"polity","id":999999.0}`},
		{"get_historical_layer", `{"year":-12345.0}`},
	} {
		r := call(tc.op, tc.payload, "2.0")
		if r.OK || r.Error.Code != "not_found" {
			t.Fatalf("domain lookup: %+v", r)
		}
	}
	before := session.simulation.StateDigest()
	for _, tc := range []struct{ op, payload string }{
		{"get_province", `{"id":0.5}`},
		{"get_province", `{"id":2147483648.0}`},
		{"get_entity", `{"kind":"polity","id":9223372036854775808.0}`},
		{"get_historical_layer", `{"year":-9000.5}`},
		{"advance", `{"years":1.0}`},
		{"apply_command", `{"sequence":1.5}`},
		{"apply_command", `{"sequence":18446744073709551616.0}`},
		{"create_world", strings.Replace(world, `"detail":4.0`, `"detail":4.5`, 1)},
		{"create_world", strings.Replace(world, `"width":24.0`, `"width":401.0`, 1)},
		{"create_world", strings.Replace(world, `"detail":4.0`, `"detail":0.0`, 1)},
		{"create_world", strings.Replace(world, `"landFraction":0.33`, `"landFraction":0.99`, 1)},
	} {
		r := call(tc.op, tc.payload, "2.0")
		if r.OK || r.Error.Code != "invalid_arguments" {
			t.Fatalf("accepted %s %s: %+v", tc.op, tc.payload, r)
		}
	}
	if session.simulation.StateDigest() != before || session.generation != 2 {
		t.Fatal("invalid requests mutated state or replaced world")
	}
	command := `{"schema":"asabiya/command-v1","profile":"native","sequence":1.0,"targetYear":-9000.0,"kind":"set_sandbox","sandbox":false,"cell":0.0}`
	r := call("apply_command", command, "2.0")
	ok(r)
	result := r.Data.(map[string]any)["result"].(map[string]any)
	if result["accepted"] != true {
		t.Fatalf("command not applied: %v", result)
	}
	r = call("advance", `{"publication":"status"}`, "2.0")
	ok(r)
	if r.Year == nil || *r.Year != -8999 {
		t.Fatal("advance must remain exactly one year")
	}
	ok(call("shutdown", `{}`, "2.0"))
	if err := <-done; err != nil {
		t.Fatal(err)
	}
}
